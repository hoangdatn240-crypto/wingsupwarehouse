package com.wingsup.warehouse.repository;

import com.wingsup.warehouse.model.AppUser;
import com.wingsup.warehouse.model.Notification;
import org.springframework.data.jpa.repository.JpaRepository;

import java.util.List;

public interface NotificationRepository
        extends JpaRepository<Notification, Long> {

    List<Notification> findByUserOrderByCreatedAtDesc(AppUser user);

    long countByUserAndReadFalse(AppUser user);
}
